"""Fetch pinned native dependencies with git when codeload tarballs are blocked.

Some cloud proxies refuse codeload.github.com (used by FetchContent URL
downloads) while allowing `git clone https://github.com/...`. This script clones
each dependency at the SHA pinned in the CMake files, applies the Macro
Oscillator patches, and writes a CMake initial-cache script that
`tools/dev.py build` passes with `-C` so FetchContent uses the local sources.

Usage: python tools/cloud/git_deps.py [--force] [--clean]
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BUILD_DIR = ROOT / "build" / "native"
CACHE_DIR = ROOT / "build" / "deps-cache"
INIT_CACHE = CACHE_DIR / "fetchcontent.cmake"
PATCHES = ROOT / "native" / "modules2" / "macro_oscillator" / "patches"
# Binary dir of native/modules2/macro_oscillator (added from engine2). Its
# CMakeLists puts `<binary>/upstream` on the include path for `stmlib/...`.
MACRO_BINARY_DIR = BUILD_DIR / "engine2" / "macro_oscillator"

# FetchContent name -> (GitHub repo, pinned SHA, patch args for apply.cmake)
DEPS: dict[str, tuple[str, str, list[str] | None]] = {
    "NLOHMANN_JSON": ("nlohmann/json", "9cca280a4d0ccf0c08f47a99aa71d1b0e52f8d03", None),
    "MACRO_EURORACK": ("pichenettes/eurorack", "f4cfa7697095a28d292bff758beb51deb49b5a86",
                       [f"-DPATCH_DIR={PATCHES}"]),
    "MACRO_STMLIB": ("pichenettes/stmlib", "e3bd7c9cc00e4364166f9905c0509b6ffd0535ec",
                     [f"-DPATCH_FILE={PATCHES / 'stmlib-msvc-inline.patch'}"]),
    "MIDI_ALSA_HEADERS": ("alsa-project/alsa-lib", "81d70a27136840fa8fb1bec6eb8e04fc1475a380", None),
    "WIRESCAPE_LIBREMIDI": ("celtera/libremidi", "390707b5d18b590509e823386f03fa712ef6ac1b", None),
}
PROBE_URL = "https://codeload.github.com/nlohmann/json/tar.gz/" + DEPS["NLOHMANN_JSON"][1]


def tarballs_reachable() -> bool:
    try:
        with urllib.request.urlopen(urllib.request.Request(PROBE_URL, method="HEAD"), timeout=20) as r:
            return 200 <= r.status < 400
    except (urllib.error.URLError, OSError):
        return False


def run(cmd: list[str], cwd: Path | None = None) -> None:
    subprocess.run(cmd, cwd=cwd, check=True)


def head(path: Path) -> str:
    out = subprocess.run(["git", "rev-parse", "HEAD"], cwd=path, capture_output=True, text=True)
    return out.stdout.strip() if out.returncode == 0 else ""


def fetch(repo: str, sha: str, dest: Path) -> None:
    if dest.is_dir() and head(dest) == sha:
        return
    shutil.rmtree(dest, ignore_errors=True)
    dest.mkdir(parents=True)
    run(["git", "init", "-q"], dest)
    run(["git", "remote", "add", "origin", f"https://github.com/{repo}"], dest)
    if subprocess.run(["git", "fetch", "-q", "--depth", "1", "origin", sha], cwd=dest).returncode != 0:
        run(["git", "fetch", "-q", "origin"], dest)  # server without SHA fetch: full history
    run(["git", "-c", "advice.detachedHead=false", "checkout", "-q", sha], dest)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--force", action="store_true", help="use git even if tarballs are reachable")
    parser.add_argument("--clean", action="store_true", help="remove the generated cache script and exit")
    args = parser.parse_args()
    if args.clean:
        INIT_CACHE.unlink(missing_ok=True)
        return 0
    if not args.force and tarballs_reachable():
        INIT_CACHE.unlink(missing_ok=True)
        print("codeload tarballs reachable; FetchContent will download normally")
        return 0
    cmake = shutil.which("cmake")
    if not cmake:
        print("cmake not found on PATH", file=sys.stderr)
        return 2
    lines = ["# Generated by tools/cloud/git_deps.py; passed to cmake with -C."]
    for name, (repo, sha, patch_args) in DEPS.items():
        dest = CACHE_DIR / f"{repo.split('/')[1]}-{sha[:8]}"
        print(f"{repo}@{sha[:8]} -> {dest.relative_to(ROOT)}")
        fetch(repo, sha, dest)
        if patch_args:
            run([cmake, f"-DSOURCE_DIR={dest}", f"-DGIT_EXECUTABLE={shutil.which('git')}", *patch_args,
                 "-P", str(PATCHES / "apply.cmake")])
        lines.append(f'set(FETCHCONTENT_SOURCE_DIR_{name} "{dest.as_posix()}" CACHE PATH "" FORCE)')
    # FetchContent ignores SOURCE_DIR when overridden, so recreate the
    # `<macro binary>/upstream/stmlib` path the include directories expect.
    stmlib = CACHE_DIR / f"stmlib-{DEPS['MACRO_STMLIB'][1][:8]}"
    link = MACRO_BINARY_DIR / "upstream" / "stmlib"
    lines += [f'file(MAKE_DIRECTORY "{link.parent.as_posix()}")',
              f'if(NOT EXISTS "{link.as_posix()}")',
              f'  file(CREATE_LINK "{stmlib.as_posix()}" "{link.as_posix()}" SYMBOLIC)',
              "endif()"]
    INIT_CACHE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {INIT_CACHE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
