import os
import subprocess
import tempfile
import unittest
from pathlib import Path

from guard import check as guard_check
from guard import linked_issue, named_paths, violations


class GuardTests(unittest.TestCase):
    def check(self, path, status='A', added=(), labels=()):
        return violations(status, [path], added, set(labels))

    def test_protected(self):
        for path in ('AGENTS.md', '.github/workflows/ci.yml', 'LICENSES/MIT.txt',
                     'native/include/wirescape/module2.h', 'docs/specs/ABI2_PLAN.md', 'tools/ci/guard.py'):
            with self.subTest(path=path):
                self.assertTrue(self.check(path))
                self.assertFalse(self.check(path, labels=['allow-protected'],
                                            added=['# SPDX-License-Identifier: GPL-3.0-only']))

    def test_issue_named_paths_unlock_protected(self):
        named = named_paths('Why\nProtected path named: `.github/workflows/ci.yml` and `docs/specs/**`\n'
                            'Protected paths named: `AGENTS.md`, `tools/ci/guard.py`\nother `x.md`')
        self.assertEqual(named, {'.github/workflows/ci.yml', 'docs/specs/**', 'AGENTS.md', 'tools/ci/guard.py'})
        spdx = ['# SPDX-License-Identifier: GPL-3.0-only']
        self.assertFalse(violations('M', ['.github/workflows/ci.yml'], spdx, set(), named))
        self.assertFalse(violations('M', ['docs/specs/ABI2_PLAN.md'], spdx, set(), named))
        self.assertTrue(violations('M', ['.github/workflows/static.yml'], spdx, set(), named))
        for path in ('AGENTS.md', 'tools/ci/guard.py', '.github/workflows/guard.yml',
                     'native/include/wirescape/module2.h', 'LICENSE'):
            with self.subTest(path=path):  # label-only paths stay locked even when named
                self.assertTrue(violations('M', [path], spdx, set(), named | {path}))
        self.assertEqual(linked_issue('Fixes stuff\n\nCloses #83'), 83)
        self.assertEqual(linked_issue('Refs #85.'), 85)
        self.assertIsNone(linked_issue('no link'))

    def test_test_removal_and_rename(self):
        self.assertTrue(self.check('native/tests/example.cpp', status='D'))
        self.assertTrue(violations('R100', ['native/tests/a.cpp', 'native/a.cpp'], [], set()))
        self.assertFalse(self.check('native/tests/a.cpp', status='D', labels=['allow-test-removal']))
        self.assertFalse(self.check('native/tests/a.cpp', status='M'))

    def test_binary_private_cannot_be_overridden(self):
        for path in ('x.DLL', 'x.exe', 'x.zip', 'x.wav', 'x.ttf', 'x.otf',
                     'x.so', 'x.dylib', 'x.lib', 'x.pdb', 'x.obj', 'x.a', 'x.woff', 'x.woff2',
                     'x.flac', 'x.mp3', 'x.aif', 'x.aiff', 'user_data/patch.json', '.tools/sdk',
                     'build/result', 'local_backups/snapshot.zip'):
            self.assertTrue(self.check(path, labels=['allow-protected', 'allow-test-removal']))
        self.assertFalse(self.check('native/ui/assets/icon.png'))

    def test_fixture_audio_allowlist(self):
        self.assertFalse(self.check('native/tests/fixtures/impulse.wav'))
        self.assertFalse(self.check('native/tests/fixtures/impulse.flac'))
        self.assertTrue(self.check('native/tests/fixtures/impulse.mp3'))
        self.assertTrue(self.check('native/tests/fixtures/icon.ttf'))
        self.assertTrue(self.check('native/tests/not-fixtures/impulse.wav'))

    def test_machine_paths(self):
        for line in ('C:' + chr(92) + 'Users' + chr(92) + 'person', 'D:' + '/Users/person/sdk', '/ho' + 'me/person/sdk'):
            self.assertTrue(self.check('tools/a.py', added=[line]))
            self.assertFalse(self.check('docs/tasks/M0-1_LOCAL.md', added=['# SPDX-License-Identifier: GPL-3.0-only', line]))
            self.assertFalse(self.check('legacy/a.py', added=[line], labels=['allow-protected']))
        self.assertFalse(self.check('README.md', added=['<!-- SPDX-License-Identifier: GPL-3.0-only -->',
                                                       '/usr/bin/python', '${HOME}/sdk']))

    def test_added_source_files_require_spdx_header(self):
        for path in ('tools/a.py', 'README.md', 'native/a.cpp', '.github/workflows/ci.yml'):
            with self.subTest(path=path):
                self.assertIn('missing SPDX header', self.check(path, added=['line 1']))

    def test_added_source_files_with_spdx_header_pass(self):
        line1 = ['# SPDX-License-Identifier: GPL-3.0-only', 'line 2']
        line3 = ['#!/usr/bin/env python3', '# generated by tool', '# SPDX-License-Identifier: GPL-3.0-only']
        line3_html = ['<!-- banner -->', '<!-- more -->', '<!-- SPDX-License-Identifier: GPL-3.0-only -->']
        for path, added in (
                ('tools/a.py', line1),
                ('README.md', line3_html),
                ('native/a.cpp', line3),
                ('.github/workflows/ci.yml', line3)):
            with self.subTest(path=path):
                self.assertNotIn('missing SPDX header', self.check(path, added=added))

    def test_spdx_exempt_added_files(self):
        for path in (
                'assets/a.json', 'assets/a.png', 'assets/a.svg', 'assets/a.ico', 'assets/a.wav', 'assets/a.flac',
                'LICENSE', 'LICENSE.md', 'LICENSES/MIT.txt', 'docs/history/note.md', 'legacy/old.txt',
                '.gitignore', '.gitattributes', '.github/CODEOWNERS', 'native/tests/fixtures/sample.cpp'):
            with self.subTest(path=path):
                self.assertNotIn('missing SPDX header', self.check(path, added=['line 1']))

    def test_modified_file_without_spdx_header_is_allowed(self):
        self.assertFalse(self.check('tools/a.py', status='M', added=['line 1']))

    def test_merge_base_diff_ignores_moved_main_changes(self):
        with tempfile.TemporaryDirectory() as td:
            repo = Path(td)
            self._git(repo, 'init', '-b', 'main')
            self._write(repo / 'docs/PLAN.md', 'base\n')
            self._write(repo / 'src/module.txt', 'base\n')
            self._git(repo, 'add', '.')
            self._git(repo, 'commit', '-m', 'base')

            self._git(repo, 'checkout', '-b', 'feature')
            self._write(repo / 'src/module.txt', 'feature change\n')
            self._git(repo, 'add', 'src/module.txt')
            self._git(repo, 'commit', '-m', 'feature change')

            self._git(repo, 'checkout', 'main')
            self._write(repo / 'docs/PLAN.md', 'main change\n')
            self._git(repo, 'add', 'docs/PLAN.md')
            self._git(repo, 'commit', '-m', 'main change')

            current = os.getcwd()
            try:
                os.chdir(repo)
                self.assertEqual([], guard_check('main', 'feature', set()))
                self._git(repo, 'checkout', '-b', 'feature2', 'main')
                self._write(repo / 'AGENTS.md', 'protected change\n')
                self._git(repo, 'add', 'AGENTS.md')
                self._git(repo, 'commit', '-m', 'protected change')
                self.assertTrue(guard_check('main', 'feature2', set()))
            finally:
                os.chdir(current)

    def _git(self, repo, *args):
        command = ['git', '-c', 'commit.gpgsign=false', '-c', 'core.hooksPath=', *args]
        if args[:2] == ('commit', '-m'):
            env = os.environ.copy()
            env.update({
                'GIT_AUTHOR_NAME': 'Test User',
                'GIT_AUTHOR_EMAIL': 'test@example.com',
                'GIT_COMMITTER_NAME': 'Test User',
                'GIT_COMMITTER_EMAIL': 'test@example.com',
            })
            subprocess.run(command, cwd=repo, check=True, text=True, capture_output=True, env=env)
            return
        subprocess.run(command, cwd=repo, check=True, text=True, capture_output=True)

    def _write(self, path, content):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf-8')


if __name__ == '__main__':
    unittest.main()
