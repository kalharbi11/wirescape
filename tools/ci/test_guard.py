import unittest
from guard import violations


class GuardTests(unittest.TestCase):
    def check(self, path, status='A', added=(), labels=()):
        return violations(status, [path], added, set(labels))

    def test_protected(self):
        for path in ('AGENTS.md', '.github/workflows/ci.yml', 'LICENSES/MIT.txt',
                     'native/include/wirescape/module2.h', 'docs/specs/ABI2_PLAN.md'):
            with self.subTest(path=path):
                self.assertTrue(self.check(path))
                self.assertFalse(self.check(path, labels=['allow-protected'],
                                            added=['# SPDX-License-Identifier: GPL-3.0-only']))

    def test_test_removal_and_rename(self):
        self.assertTrue(self.check('native/tests/example.cpp', status='D'))
        self.assertTrue(violations('R100', ['native/tests/a.cpp', 'native/a.cpp'], [], set()))
        self.assertFalse(self.check('native/tests/a.cpp', status='D', labels=['allow-test-removal']))
        self.assertFalse(self.check('native/tests/a.cpp', status='M'))

    def test_binary_private_cannot_be_overridden(self):
        for path in ('x.DLL', 'x.exe', 'x.zip', 'x.wav', 'x.ttf', 'x.otf',
                     'user_data/patch.json', '.tools/sdk', 'build/result'):
            self.assertTrue(self.check(path, labels=['allow-protected', 'allow-test-removal']))
        self.assertFalse(self.check('native/ui/assets/icon.png'))

    def test_machine_paths(self):
        for line in ('C:' + chr(92) + 'Users' + chr(92) + 'person', 'D:' + '/Users/person/sdk', '/ho' + 'me/person/sdk'):
            self.assertTrue(self.check('tools/a.py', added=[line]))
            self.assertFalse(self.check('docs/tasks/M0-1_LOCAL.md', added=['# SPDX-License-Identifier: GPL-3.0-only', line]))
            self.assertFalse(self.check('legacy/a.py', added=[line], labels=['allow-protected']))
        self.assertFalse(self.check('README.md', added=['<!-- SPDX-License-Identifier: GPL-3.0-only -->',
                                                       '/usr/bin/python', '${HOME}/sdk']))

    def test_added_source_files_require_spdx_header(self):
        for path in ('tools/a.py', 'README.md', 'native/a.cpp', '.github/workflows/ci.yml'):
            with self.subTest(path=path):
                self.assertIn('missing SPDX header', self.check(path, added=['line 1']))

    def test_added_source_files_with_spdx_header_pass(self):
        line1 = ['# SPDX-License-Identifier: GPL-3.0-only', 'line 2']
        line3 = ['#!/usr/bin/env python3', '# generated by tool', '# SPDX-License-Identifier: GPL-3.0-only']
        line3_html = ['<!-- banner -->', '<!-- more -->', '<!-- SPDX-License-Identifier: GPL-3.0-only -->']
        for path, added in (
                ('tools/a.py', line1),
                ('README.md', line3_html),
                ('native/a.cpp', line3),
                ('.github/workflows/ci.yml', line3)):
            with self.subTest(path=path):
                self.assertNotIn('missing SPDX header', self.check(path, added=added))

    def test_spdx_exempt_added_files(self):
        for path in (
                'assets/a.json', 'assets/a.png', 'assets/a.svg', 'assets/a.ico', 'assets/a.wav', 'assets/a.flac',
                'LICENSE', 'LICENSE.md', 'LICENSES/MIT.txt', 'docs/history/note.md', 'legacy/old.txt',
                '.gitignore', '.gitattributes', '.github/CODEOWNERS', 'native/tests/fixtures/sample.cpp'):
            with self.subTest(path=path):
                self.assertNotIn('missing SPDX header', self.check(path, added=['line 1']))

    def test_modified_file_without_spdx_header_is_allowed(self):
        self.assertFalse(self.check('tools/a.py', status='M', added=['line 1']))


if __name__ == '__main__':
    unittest.main()
